import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { validateCatalog } from '../site/source-model.mjs';

const directory = new URL('../sources/', import.meta.url);
const names = (await readdir(directory)).filter(name => name.endsWith('.json')).sort();
if (!names.length) throw new Error('sources/ 中至少需要一个检测源。');
const values = [];
for (const name of names) {
  const value = JSON.parse(await readFile(new URL(name, directory), 'utf8'));
  if (name !== `${value.id}.json`) throw new Error(`文件名必须与 id 一致：${name}`);
  values.push(value);
}
const sources = validateCatalog(values);
const target = new URL('../site/catalog.js', import.meta.url);
await writeFile(target, `// Generated by npm run build. Edit sources/*.json instead.\nexport default ${JSON.stringify(sources, null, 2)};\n`);
const hash = createHash('sha256').update(JSON.stringify(sources));
for (const file of ['app.js','styles.css','source-model.mjs','config.js']) hash.update(await readFile(new URL(`../site/${file}`,import.meta.url)));
const version = hash.digest('hex').slice(0,12);
const index = new URL('../site/index.html', import.meta.url);
const html = await readFile(index,'utf8');
await writeFile(index,html.replace(/(styles\.css|app\.js)\?v=[^"\s]+/g,`$1?v=${version}`));
console.log(`Built ${sources.length} sources → ${fileURLToPath(target)}`);
